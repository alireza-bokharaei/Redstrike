PROFILE = TLSProbeProfile(
    allowed_ports=(443, 8443),
    timeout_sec=5.0,
    protocols=("TLSv1.3", "TLSv1.2", "TLSv1.1", "TLSv1"),
    deprecated=frozenset({"TLSv1", "TLSv1.1", "SSLv3"}),
)


@pytest.fixture()
def tls_server(tmp_path):
    """Start a loopback TLS server; yield (port, clean_stop)."""
    if OPENSSL is None:
        pytest.skip("openssl binary is required to mint a certificate")
    cert, key = tmp_path / "srv.pem", tmp_path / "srv.key"
    subprocess.run(
        [
            OPENSSL, "req", "-x509", "-newkey", "rsa:2048", "-keyout", str(key),
            "-out", str(cert), "-days", "2", "-nodes", "-subj", "/CN=unit.lab.example",
            "-addext", "subjectAltName=DNS:unit.lab.example",
        ],
        check=True,
        capture_output=True,
    )
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(str(cert), str(key))
    listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    listener.bind(("127.0.0.1", 0))
    listener.listen(16)
    port = listener.getsockname()[1]
    stop = threading.Event()

    def serve() -> None:
        listener.settimeout(0.3)
        while not stop.is_set():
            try:
                conn, _ = listener.accept()
            except (TimeoutError, OSError):
                continue
            try:
                with ctx.wrap_socket(conn, server_side=True) as tls_conn:
                    tls_conn.settimeout(1.0)
                    try:
                        tls_conn.recv(64)
                    except OSError:
                        pass
            except (ssl.SSLError, OSError):
                conn.close()

    thread = threading.Thread(target=serve, daemon=True)
    thread.start()
    try:
        yield port
    finally:
        stop.set()
        listener.close()
        thread.join(timeout=2)


