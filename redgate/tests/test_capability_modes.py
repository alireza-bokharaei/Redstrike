async def test_admin_toggle_disables_a_mode_but_never_enables_a_forbidden_capability(
    ws, registry
):
    ok, _ = registry.mode_enabled(ws.db, "pentest")
    assert ok

    toggle = await ws.client.post(
        "/api/v1/capabilities/toggle",
        headers=ws.headers["admin"],
        json={"enabled": True, "modes": ["assessment"]},
    )
    assert toggle.status_code == 200, toggle.text
    assert registry.mode_enabled(ws.db, "pentest") == (
        False,
        "Mode 'pentest' is not on the administrator's allow-list.",
    )
    allowed, _ = registry.mode_enabled(ws.db, "assessment")
    assert allowed

    # A mode can never gain a capability the code-level policy does not implement.
    decision = registry.resolve(ws.db, "assessment", "binary_hardening_triage")
    assert decision.allowed is False


