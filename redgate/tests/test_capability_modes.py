async def test_expansion_is_pending_and_changes_nothing_until_approved(ws):
    service = _expansion_service(ws)
    result = service.submit(
        principal=ws.owner,
        engagement_id="ENG-A",
        kind="targets",
        targets=["198.51.100.77"],
        roe_clause="related_assets",
        justification="Sibling host in the same documented asset group.",
    )
    assert result.pending is True
    allowed = ws.rt.scope.evaluate_target("ENG-A", "198.51.100.77", resolve_dns=False)
    assert allowed.allowed is False, "approval has not happened yet"

    approved = service.decide(
        expansion_id=result.request_id,
        principal=ws.rt.auth.get_operator("admin"),
        decision="approved",
        note="Verified against the signed RoE.",  # noqa: E501
    )
