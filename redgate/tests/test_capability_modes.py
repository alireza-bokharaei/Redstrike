# Binary hardening triage
# ---------------------------------------------------------------------------
def _elf64(
    *,
    pie: bool,
    execstack: bool,
    wx: bool,
    relro: bool,
    bind_now: bool,
    rpath: str | None = None,
) -> bytes:
    """Build a structurally valid ELF64 image for the parser under test."""
    ident = b"\x7fELF" + bytes([2, 1, 1, 0]) + b"\x00" * 8
    phoff, phentsize = 64, 56
    dyn_off, dyn_size = 0x300, 0x80
    str_off = 0x380
    strtab = b"\x00" + (rpath.encode() + b"\x00" if rpath else b"")

    phdrs: list[bytes] = [
        # PT_LOAD spanning the whole image (RWX when `wx` is requested).
        struct.pack(
            "<IIQQQQQQ", 1, 0x4 | 0x2 | (0x1 if wx else 0), 0, 0x400000, 0x400000,
            0x400, 0x400, 0x1000,
        ),
        struct.pack(
            "<IIQQQQQQ", 2, 0x4, dyn_off, 0x400000 + dyn_off, 0x400000 + dyn_off,
            dyn_size, dyn_size, 0x8,
        ),
    ]
    if relro:
        phdrs.append(
            struct.pack(
                "<IIQQQQQQ", 0x6474E552, 0x4, 0x400, 0x400400, 0x400400, 0x40, 0x40, 0x1
            )
        )
    phdrs.append(
        struct.pack(
            "<IIQQQQQQ", 0x6474E551, 0x6 | (0x1 if execstack else 0), 0, 0, 0, 0, 0, 0x10
        )
    )

    dyn: list[bytes] = []
    if rpath:
        dyn.append(struct.pack("<qQ", 15, 1))  # DT_RPATH -> offset *inside* strtab
    dyn.append(struct.pack("<qQ", 30, 0x8 if bind_now else 0))  # DT_FLAGS
    dyn.append(struct.pack("<qQ", 5, 0x400000 + str_off))  # DT_STRTAB
    dyn.append(struct.pack("<qQ", 0, 0))
    dynamic = b"".join(dyn)

    header = ident + struct.pack(
        "<HHIQQQIHHHHHH",
        3 if pie else 2, 0x3E, 1, 0x400000, phoff, 0, 0, 64,
        phentsize, len(phdrs), 64, 0, 0,
    )
    blob = bytearray(0x400)
    blob[0 : len(header)] = header
    for index, entry in enumerate(phdrs):
        offset = phoff + index * phentsize
        blob[offset : offset + phentsize] = entry
    blob[dyn_off : dyn_off + len(dynamic)] = dynamic
    blob[str_off : str_off + len(strtab)] = strtab
    return bytes(blob)


