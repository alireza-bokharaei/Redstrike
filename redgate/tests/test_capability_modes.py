    now_allowed = ws.rt.scope.evaluate_target("ENG-A", "198.51.100.77", resolve_dns=False)
    assert now_allowed.allowed is True
    assert "198.51.100.77" in approved["applied"]["targets_added"]
    assert ws.db.verify_audit_chain()["valid"]


