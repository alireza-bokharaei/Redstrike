def test_manifest_declares_the_documented_modes(registry):
    assert set(registry.mode_ids()) == {
        "vulnerability_discovery",
        "bug_bounty",
        "pentest",
        "ctf",
        "assessment",
        "ssl_tls_analysis",
    }
    assert registry.manifest_version == "2.3"
    for mode in registry.describe():
        assert mode["ceiling"]["max_actions"] <= 128
        assert mode["ceiling"]["max_hosts"] <= 8


def test_tls_deep_analysis_is_mandatory_for_every_tls_mode(registry):
    """The prompt makes TLS analysis non-optional; the manifest must enforce it."""
    for mode_id in ("vulnerability_discovery", "bug_bounty", "pentest", "assessment"):
        mode = registry.get_mode(mode_id)
        assert "tls_deep_analysis" in mode.mandatory_capabilities
        assert mode.allows("tls_deep_analysis")
    # CTF is an offline scenario: the capability is available but not mandatory.
    assert registry.get_mode("ctf").mandatory_capabilities == frozenset()


